//! Decoder for UEdGraphNode pin data - the node-to-node wiring of a Blueprint graph.
//!
//! A graph node's tagged properties hold its class, position and member
//! reference; its pins live in the native payload that follows, written by
//! UEdGraphPin::SerializeAsOwningNode. Each pin carries its own type, default
//! value and the pins it is linked to, so decoding this block is what turns a
//! list of nodes into a connected graph.
//!
//! Layout follows UEdGraphPin::SerializePinArray / UEdGraphPin::Serialize and
//! FEdGraphPinType::Serialize in Engine/Source/Runtime/Engine/Private/EdGraph/EdGraphPin.cpp.

use super::archive::{decode_err, Reader, Res, Val};
use super::package::{ObjectExport, Package};
use super::properties::read_text;

// Custom version GUIDs, from Engine/Source/Runtime/Core/Private/UObject/DevObjectVersion.cpp
const FRAMEWORK_OBJECT_VERSION: &str = "CFFC743F43B04480939114DF171D2073";
const RELEASE_OBJECT_VERSION: &str = "9C54D522A8264FBE9421074661B482D0";
const BLUEPRINTS_OBJECT_VERSION: &str = "B0D832E41F894F0DACCF7EB736FD4AA2";
const UE5_MAIN_STREAM_OBJECT_VERSION: &str = "697DD581E64F41ABAA4A51ECBEB7B628";
const UE5_RELEASE_STREAM_OBJECT_VERSION: &str = "D89B5E4224BD4D468412ACA8DF641779";

// Enum values of those versions
const FRAMEWORK_EDGRAPH_PIN_CONTAINER_TYPE: i32 = 26;
const FRAMEWORK_PINS_STORE_FNAME: i32 = 31;
const RELEASE_PIN_TYPE_INCLUDES_UOBJECT_WRAPPER: i32 = 32;
const BLUEPRINTS_ADVANCED_CONTAINER_SUPPORT: i32 = 6;
const BLUEPRINTS_EDGRAPH_PIN_OPTIMIZED: i32 = 4;
const UE5_MAIN_EDGRAPH_PIN_SOURCE_INDEX: i32 = 50;
const UE5_RELEASE_SERIALIZE_FLOAT_PIN_DEFAULTS_SINGLE: i32 = 36;

const VER_UE4_MEMBERREFERENCE_IN_PINTYPE: i32 = 328;
const VER_UE4_SERIALIZE_PINTYPE_CONST: i32 = 341;
const VER_UE4_EDGRAPHPINTYPE_SERIALIZATION: i32 = 297;
const VER_UE4_FTEXT_HISTORY: i32 = 368;

/// Node classes may append their own data after the pins - UK2Node_EditablePinBase
/// writes its UserDefinedPins array, for instance - so a small tail is expected.
const MAX_SUBCLASS_TRAILING_BYTES: usize = 4096;

fn direction_name(d: u8) -> Val {
    match d {
        0 => Val::str("Input"),
        1 => Val::str("Output"),
        _ => Val::Int(d as i64),
    }
}

fn container_name(c: u8) -> Val {
    match c {
        0 => Val::str("None"),
        1 => Val::str("Array"),
        2 => Val::str("Set"),
        3 => Val::str("Map"),
        _ => Val::Int(c as i64),
    }
}

/// A pin serialized by reference: owning node plus pin id, no body.
#[derive(Debug, Clone)]
pub struct PinRef {
    pub node: String,
    pub pin_id: String,
    /// The linked pin's name, once every node is decoded (`linked_to` only).
    pub pin: Option<String>,
}

impl PinRef {
    fn to_val(&self) -> Val {
        let mut m = vec![("node", Val::str(&self.node)), ("pin_id", Val::str(&self.pin_id))];
        if let Some(p) = &self.pin {
            m.push(("pin", Val::str(p)));
        }
        Val::map(m)
    }
}

#[derive(Debug, Clone)]
pub struct Pin {
    pub owning_node: String,
    pub pin_id: String,
    pub name: String,
    pub direction: Val,
    /// FEdGraphPinType, field by field.
    pub ty: Val,
    pub default_value: String,
    pub default_object: String,
    pub linked_to: Vec<PinRef>,
    /// Everything else the pin body holds, in serialized order.
    rest: Vec<(&'static str, Val)>,
    sub_pins: Vec<PinRef>,
    parent_pin: Option<PinRef>,
    reference_pass_through: Option<PinRef>,
    flags: Vec<(&'static str, Val)>,
}

impl Pin {
    /// The pin as the Python reader returns it, key for key.
    pub fn to_val(&self) -> Val {
        let opt = |r: &Option<PinRef>| r.as_ref().map(|r| r.to_val()).unwrap_or(Val::Null);
        let mut m: Vec<(&str, Val)> = vec![
            ("owning_node", Val::str(&self.owning_node)),
            ("pin_id", Val::str(&self.pin_id)),
            ("name", Val::str(&self.name)),
        ];
        let rest = |key: &str| self.rest.iter().find(|(k, _)| *k == key).map(|(_, v)| v.clone());
        if let Some(v) = rest("friendly_name") {
            m.push(("friendly_name", v));
        }
        if let Some(v) = rest("source_index") {
            m.push(("source_index", v));
        }
        m.push(("tooltip", rest("tooltip").unwrap_or(Val::str(""))));
        m.push(("direction", self.direction.clone()));
        m.push(("type", self.ty.clone()));
        m.push(("default_value", Val::str(&self.default_value)));
        m.push(("autogenerated_default_value", rest("autogenerated_default_value").unwrap_or(Val::str(""))));
        m.push(("default_object", Val::str(&self.default_object)));
        m.push(("default_text_value", rest("default_text_value").unwrap_or(Val::Null)));
        m.push(("linked_to", Val::List(self.linked_to.iter().map(|r| r.to_val()).collect())));
        m.push(("sub_pins", Val::List(self.sub_pins.iter().map(|r| r.to_val()).collect())));
        m.push(("parent_pin", opt(&self.parent_pin)));
        m.push(("reference_pass_through", opt(&self.reference_pass_through)));
        m.extend(self.flags.iter().cloned());
        Val::map(m)
    }

    pub fn rest(&self, key: &str) -> Option<&Val> {
        self.rest.iter().find(|(k, _)| *k == key).map(|(_, v)| v)
    }

    pub fn flag(&self, key: &str) -> bool {
        self.flags.iter().any(|(k, v)| *k == key && *v == Val::Bool(true))
    }
}

/// Decodes the pin block of graph nodes in one package.
struct PinDecoder<'p> {
    package: &'p Package,
}

impl<'p> PinDecoder<'p> {
    fn custom_version(&self, guid: &str) -> i32 {
        self.package.summary.custom_version(guid)
    }

    fn has_pins(&self) -> bool {
        self.custom_version(BLUEPRINTS_OBJECT_VERSION) >= BLUEPRINTS_EDGRAPH_PIN_OPTIMIZED
    }

    fn pins_store_fname(&self) -> bool {
        self.custom_version(FRAMEWORK_OBJECT_VERSION) >= FRAMEWORK_PINS_STORE_FNAME
    }

    fn filter_editor_only(&self) -> bool {
        self.package.summary.filter_editor_only
    }

    fn name_or_string(&self, ar: &mut Reader) -> Res<String> {
        if self.pins_store_fname() {
            ar.name()
        } else {
            ar.fstring()
        }
    }

    fn object(&self, ar: &mut Reader) -> Res<String> {
        Ok(self.package.resolve_index(ar.package_index()?))
    }

    fn text(&self, ar: &mut Reader) -> Res<Val> {
        if self.package.summary.file_version_ue4 < VER_UE4_FTEXT_HISTORY {
            return decode_err("pre-history FText is not supported".into());
        }
        read_text(ar, self.package)
    }

    /// FMemberReference as it lands in a pin type: parent, name and guid only.
    fn member_reference(&self, ar: &mut Reader) -> Res<Val> {
        Ok(Val::map(vec![
            ("MemberParent", Val::Str(self.object(ar)?)),
            ("MemberName", Val::Str(ar.name()?)),
            ("MemberGuid", Val::Str(ar.guid()?)),
        ]))
    }

    fn terminal_type(&self, ar: &mut Reader) -> Res<Val> {
        let mut t = vec![
            ("TerminalCategory", Val::Str(self.name_or_string(ar)?)),
            ("TerminalSubCategory", Val::Str(self.name_or_string(ar)?)),
            ("TerminalSubCategoryObject", Val::Str(self.object(ar)?)),
            ("bTerminalIsConst", Val::Bool(ar.bool32()?)),
            ("bTerminalIsWeakPointer", Val::Bool(ar.bool32()?)),
        ];
        if self.custom_version(RELEASE_OBJECT_VERSION) >= RELEASE_PIN_TYPE_INCLUDES_UOBJECT_WRAPPER {
            t.push(("bTerminalIsUObjectWrapper", Val::Bool(ar.bool32()?)));
        }
        Ok(Val::map(t))
    }

    fn pin_type(&self, ar: &mut Reader) -> Res<Val> {
        if self.package.summary.file_version_ue4 < VER_UE4_EDGRAPHPINTYPE_SERIALIZATION {
            return decode_err("pin type predates native serialization".into());
        }
        let mut t = vec![
            ("PinCategory", Val::Str(self.name_or_string(ar)?)),
            ("PinSubCategory", Val::Str(self.name_or_string(ar)?)),
            ("PinSubCategoryObject", Val::Str(self.object(ar)?)),
        ];
        if self.custom_version(FRAMEWORK_OBJECT_VERSION) >= FRAMEWORK_EDGRAPH_PIN_CONTAINER_TYPE {
            let container = ar.u8()?;
            t.push(("ContainerType", container_name(container)));
            if container == 3 {
                t.push(("PinValueType", self.terminal_type(ar)?));
            }
        } else {
            let (mut is_map, mut is_set) = (false, false);
            let mut value_type = None;
            if self.custom_version(BLUEPRINTS_OBJECT_VERSION) >= BLUEPRINTS_ADVANCED_CONTAINER_SUPPORT {
                is_map = ar.bool32()?;
                if is_map {
                    value_type = Some(self.terminal_type(ar)?);
                }
                is_set = ar.bool32()?;
            }
            let is_array = ar.bool32()?;
            if let Some(v) = value_type {
                t.push(("PinValueType", v));
            }
            let c = if is_map { "Map" } else if is_set { "Set" } else if is_array { "Array" } else { "None" };
            t.push(("ContainerType", Val::str(c)));
        }
        t.push(("bIsReference", Val::Bool(ar.bool32()?)));
        t.push(("bIsWeakPointer", Val::Bool(ar.bool32()?)));
        if self.package.summary.file_version_ue4 >= VER_UE4_MEMBERREFERENCE_IN_PINTYPE {
            t.push(("MemberReference", self.member_reference(ar)?));
        }
        if self.package.summary.file_version_ue4 >= VER_UE4_SERIALIZE_PINTYPE_CONST {
            t.push(("bIsConst", Val::Bool(ar.bool32()?)));
        }
        if self.custom_version(RELEASE_OBJECT_VERSION) >= RELEASE_PIN_TYPE_INCLUDES_UOBJECT_WRAPPER {
            t.push(("bIsUObjectWrapper", Val::Bool(ar.bool32()?)));
        }
        if self.custom_version(UE5_RELEASE_STREAM_OBJECT_VERSION) >= UE5_RELEASE_SERIALIZE_FLOAT_PIN_DEFAULTS_SINGLE {
            t.push(("bSerializeAsSinglePrecisionFloat", Val::Bool(ar.bool32()?)));
        }
        Ok(Val::map(t))
    }

    fn pin_reference(&self, ar: &mut Reader) -> Res<Option<PinRef>> {
        if ar.bool32()? {
            return Ok(None); // bNullPtr
        }
        let node = self.object(ar)?;
        let pin_id = ar.guid()?;
        Ok(Some(PinRef { node, pin_id, pin: None }))
    }

    fn pin_reference_array(&self, ar: &mut Reader) -> Res<Vec<PinRef>> {
        let count = ar.i32()?;
        if !(0..=1 << 16).contains(&count) {
            return decode_err(format!("implausible pin reference count {count}"));
        }
        let mut out = Vec::new();
        for _ in 0..count {
            if let Some(r) = self.pin_reference(ar)? {
                out.push(r);
            }
        }
        Ok(out)
    }

    fn pin_body(&self, ar: &mut Reader) -> Res<Pin> {
        let owning_node = self.object(ar)?;
        let pin_id = ar.guid()?;
        let name = self.name_or_string(ar)?;
        let mut rest: Vec<(&'static str, Val)> = Vec::new();
        if !self.filter_editor_only() {
            rest.push(("friendly_name", self.text(ar)?));
        }
        if self.custom_version(UE5_MAIN_STREAM_OBJECT_VERSION) >= UE5_MAIN_EDGRAPH_PIN_SOURCE_INDEX {
            rest.push(("source_index", Val::Int(ar.i32()? as i64)));
        }
        rest.push(("tooltip", Val::Str(ar.fstring()?)));
        let direction = direction_name(ar.u8()?);
        let ty = self.pin_type(ar)?;
        let default_value = ar.fstring()?;
        rest.push(("autogenerated_default_value", Val::Str(ar.fstring()?)));
        let default_object = self.object(ar)?;
        rest.push(("default_text_value", self.text(ar)?));
        let linked_to = self.pin_reference_array(ar)?;
        let sub_pins = self.pin_reference_array(ar)?;
        let parent_pin = self.pin_reference(ar)?;
        let reference_pass_through = self.pin_reference(ar)?;
        let mut flags = Vec::new();
        if !self.filter_editor_only() {
            flags.push(("persistent_guid", Val::Str(ar.guid()?)));
            let bits = ar.u32()?;
            for (bit, key) in [
                (1, "hidden"),
                (2, "not_connectable"),
                (4, "default_value_read_only"),
                (8, "default_value_ignored"),
                (16, "advanced_view"),
                (32, "orphaned"),
            ] {
                flags.push((key, Val::Bool(bits & bit != 0)));
            }
        }
        Ok(Pin {
            owning_node,
            pin_id,
            name,
            direction,
            ty,
            default_value,
            default_object,
            linked_to,
            rest,
            sub_pins,
            parent_pin,
            reference_pass_through,
            flags,
        })
    }

    fn owned_pin(&self, ar: &mut Reader) -> Res<Option<Pin>> {
        if ar.bool32()? {
            return Ok(None); // bNullPtr
        }
        self.object(ar)?; // owning node, repeated inside the body
        ar.guid()?; // pin id, repeated inside the body
        Ok(Some(self.pin_body(ar)?))
    }

    fn read_pins_block(&self, ar: &mut Reader) -> Res<Vec<Pin>> {
        let count = ar.i32()?;
        if !(0..=1 << 14).contains(&count) {
            return decode_err(format!("implausible pin count {count}"));
        }
        let mut out = Vec::new();
        for _ in 0..count {
            if let Some(p) = self.owned_pin(ar)? {
                out.push(p);
            }
        }
        Ok(out)
    }

    /// One node's pins; fails unless the block ends near the export end.
    fn try_export(&self, export: &ObjectExport) -> Res<Vec<Pin>> {
        let data = self.package.export_data(export);
        let start = export.script_end;
        if start <= 0 || start as usize >= data.len() {
            return decode_err("export has no native payload after its properties".into());
        }
        let mut ar = Reader::new(data, &self.package.names);
        ar.seek(start)?;
        // UObject::Serialize ends with FLazyObjectPtr::PossiblySerializeObjectGuid, which
        // writes a 4-byte bool and, when set, the object's FUniqueObjectGuid.
        if ar.bool32()? {
            ar.guid()?;
        }
        let pins = self.read_pins_block(&mut ar)?;
        let trailing = data.len() - ar.tell();
        if trailing > MAX_SUBCLASS_TRAILING_BYTES {
            return decode_err(format!("pin block ended at {} of {} bytes", ar.tell(), data.len()));
        }
        Ok(pins)
    }
}

/// An FEdGraphPinType stored as a property value (a Blueprint variable's type).
pub fn read_pin_type(ar: &mut Reader, package: &Package) -> Res<Val> {
    PinDecoder { package }.pin_type(ar)
}

/// True when the export's class looks like a UEdGraphNode subclass.
pub fn is_graph_node(package: &Package, export: &ObjectExport) -> bool {
    let class_name = package.export_class(export);
    let leaf = class_name.rsplit('.').next().unwrap_or("");
    if leaf.starts_with("AnimGraphNodeBinding") {
        return false; // a binding object, not a graph node
    }
    [
        "K2Node",
        "EdGraphNode",
        "MaterialGraphNode",
        "AnimGraphNode",
        "NiagaraNode",
        "SoundCueGraphNode",
        "BehaviorTreeGraphNode",
    ]
    .iter()
    .any(|p| leaf.starts_with(p))
}

pub struct GraphNode {
    pub export: usize,
    pub path: String,
    pub class: String,
    /// None when the pin block could not be decoded.
    pub pins: Option<Vec<Pin>>,
}

/// Decodes every graph node in the package and resolves pin links to names.
pub fn read_graph(package: &Package) -> Vec<GraphNode> {
    let decoder = PinDecoder { package };
    if !decoder.has_pins() {
        return Vec::new();
    }
    let mut nodes = Vec::new();
    let mut pin_names: std::collections::HashMap<(String, String), String> = std::collections::HashMap::new();
    for (index, export) in package.exports.iter().enumerate() {
        if !is_graph_node(package, export) {
            continue;
        }
        let pins = decoder.try_export(export).ok();
        for pin in pins.iter().flatten() {
            pin_names.insert((pin.owning_node.clone(), pin.pin_id.clone()), pin.name.clone());
        }
        nodes.push(GraphNode { export: index, path: package.export_path(index), class: package.export_class(export), pins });
    }
    for node in &mut nodes {
        for pin in node.pins.iter_mut().flatten() {
            for link in &mut pin.linked_to {
                let name = pin_names.get(&(link.node.clone(), link.pin_id.clone()));
                link.pin = Some(name.cloned().unwrap_or_else(|| "<unknown>".into()));
            }
        }
    }
    nodes
}

/// The graph as the Python reader returns it: {node path: {class, pins}}.
pub fn graph_val(nodes: &[GraphNode]) -> Val {
    Val::Map(
        nodes
            .iter()
            .map(|n| {
                let mut m = vec![("class", Val::str(&n.class))];
                match &n.pins {
                    Some(pins) => m.push(("pins", Val::List(pins.iter().map(|p| p.to_val()).collect()))),
                    None => {
                        m.push(("pins", Val::Null));
                        m.push(("error", Val::str("pin block could not be decoded")));
                    }
                }
                (n.path.clone(), Val::map(m))
            })
            .collect(),
    )
}

/// Flattens decoded nodes into (from node, from pin, to node, to pin).
pub fn connections(nodes: &[GraphNode]) -> Vec<(String, String, String, String)> {
    let mut out = Vec::new();
    for node in nodes {
        for pin in node.pins.iter().flatten() {
            if pin.direction != Val::str("Output") {
                continue;
            }
            for link in &pin.linked_to {
                out.push((
                    node.path.clone(),
                    pin.name.clone(),
                    link.node.clone(),
                    link.pin.clone().unwrap_or_else(|| "<unknown>".into()),
                ));
            }
        }
    }
    out
}
